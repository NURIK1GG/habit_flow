import { test, expect } from '@playwright/test';
test('weekly goal persists and milestones follow check-in and undo', async ({page}) => {
 await page.goto('/account/register');
 await page.getByLabel('Display name').fill('Aidos Sapar');
 await page.getByLabel('Email address').fill(`goals-${Date.now()}@example.com`);
 await page.getByLabel('Password',{exact:true}).fill('Demo!Pass123');
 await page.getByRole('button',{name:'Start building momentum'}).click();
 await expect(page.locator('[data-interactive-ready="true"]')).toBeAttached();
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByLabel('Weekly check-in goal').fill('1');
 await page.getByRole('button',{name:'Save preferences'}).click();
 await expect(page.locator('.toast-body')).toContainText('saved');
 await page.reload(); await expect(page.getByLabel('Weekly check-in goal')).toHaveValue('1');
 await page.getByRole('link',{name:'Overview',exact:true}).click();
 await expect(page.locator('.goal-numbers>strong')).toHaveText('0 / 1');
 await page.getByRole('button',{name:'New routine'}).click();
 await page.getByLabel('Routine name').fill('Evening walk');
 await page.getByRole('button',{name:'Save routine'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.locator('.routine-card').getByRole('button',{name:'Check in'}).click();
 await page.getByRole('button',{name:'Save check-in'}).click();
 await expect(page.locator('.goal-numbers>strong')).toHaveText('1 / 1');
 await expect(page.locator('.achievement.earned').filter({has:page.getByRole('heading',{name:'First step',exact:true})})).toHaveCount(1);
 await page.getByRole('link',{name:'Progress',exact:true}).click();
 await page.locator('.history-row').getByRole('button',{name:'Undo'}).click();
 await expect(page.locator('.goal-numbers>strong')).toHaveText('0 / 1');
 await expect(page.locator('.achievement.earned')).toHaveCount(0);
 await page.getByRole('button',{name:'Toggle dark theme'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-bs-theme','dark');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)).toBe(false);
});
